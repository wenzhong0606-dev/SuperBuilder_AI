                {
                    TenantId = 0,
                    Culture = locale.Culture,
                    ResourceKey = key,
                    Value = value,
                    Description = key.StartsWith("Common.") ? "系统通用文本" : "系统界面文本",
                    IsTranslated = true,
                });
            }

            _db.UiTextResources.AddRange(toAdd);
        }

        await _db.SaveChangesAsync(ct);
