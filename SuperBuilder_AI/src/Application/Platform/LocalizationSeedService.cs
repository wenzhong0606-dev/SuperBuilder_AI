                if (defaults.TryGetValue(locale.Culture, out var hand) && hand.TryGetValue(key, out var hv))
                    value = hv;
                else if (locale.Culture == "zh-CN" && ZhCnDefaults.TryGetValue(key, out var zv))
                    value = zv;
                else if (enUs.TryGetValue(key, out var ev))
                    value = ev;
                else
                    value = key;

